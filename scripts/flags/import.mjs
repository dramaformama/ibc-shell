#!/usr/bin/env node
// Imports circle-flags (MIT) SVGs into ui/static/flags, optimizes them with SVGO,
// and regenerates the code registries (ui/src/lib/flags/codes.ts, crates/store/src/flags_list.rs).
// Usage: node scripts/flags/import.mjs
// Re-running is idempotent for a pinned version; bump CIRCLE_FLAGS_VERSION + sha256 together.

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import {
	copyFileSync,
	mkdirSync,
	mkdtempSync,
	readFileSync,
	readdirSync,
	rmSync,
	statSync,
	writeFileSync
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const CIRCLE_FLAGS_VERSION = '2.8.0';
const TARBALL_URL = `https://codeload.github.com/HatScripts/circle-flags/tar.gz/refs/tags/v${CIRCLE_FLAGS_VERSION}`;
const TARBALL_SHA256 = '8e939cec80c1910ef27448072d0fa9822040f35f0566cb76c133326ff989e98f';
const SVGO_VERSION = '4.1.0';
const SIZE_BUDGET_BYTES = 400 * 1024;
// ISO 3166-1 alpha-2 (incl. circle-flags extras eu, un, xx) plus UK home nations.
const SUBDIVISION_CODES = ['gb-eng', 'gb-nir', 'gb-sct', 'gb-wls'];

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const OUT_SVG = join(ROOT, 'ui/static/flags');
const OUT_TS = join(ROOT, 'ui/src/lib/flags/codes.ts');
const OUT_RS = join(ROOT, 'crates/store/src/flags_list.rs');

const work = mkdtempSync(join(tmpdir(), 'termlite-flags-'));
try {
	const bytes = Buffer.from(await (await fetch(TARBALL_URL)).arrayBuffer());
	const sha = createHash('sha256').update(bytes).digest('hex');
	if (sha !== TARBALL_SHA256) {
		throw new Error(`sha256 mismatch for ${TARBALL_URL}: got ${sha}`);
	}
	const tarPath = join(work, 'circle-flags.tar.gz');
	writeFileSync(tarPath, bytes);
	const extractDir = join(work, 'extract');
	mkdirSync(extractDir);
	execFileSync('tar', ['-xzf', tarPath, '-C', extractDir]);

	const pkgDir = join(extractDir, `circle-flags-${CIRCLE_FLAGS_VERSION}`);
	const flagDir = join(pkgDir, 'flags');
	const available = new Set(
		readdirSync(flagDir)
			.filter((f) => f.endsWith('.svg'))
			.map((f) => f.slice(0, -'.svg'.length))
	);
	const codes = [...available]
		.filter((c) => /^[a-z]{2}$/.test(c) || SUBDIVISION_CODES.includes(c))
		.sort();
	for (const sub of SUBDIVISION_CODES) {
		if (!available.has(sub)) throw new Error(`expected subdivision ${sub} missing upstream`);
	}

	const staged = join(work, 'staged');
	mkdirSync(staged);
	for (const c of codes) copyFileSync(join(flagDir, `${c}.svg`), join(staged, `${c}.svg`));

	const optimized = join(work, 'optimized');
	mkdirSync(optimized);
	const svgoDir = join(work, 'svgo-tool');
	mkdirSync(svgoDir);
	execFileSync(
		'npm',
		['install', '--prefix', svgoDir, '--no-audit', '--no-fund', `svgo@${SVGO_VERSION}`],
		{ stdio: 'inherit', shell: process.platform === 'win32' }
	);
	execFileSync(
		process.execPath,
		[
			join(svgoDir, 'node_modules/svgo/bin/svgo.js'),
			'--multipass',
			'-f',
			staged,
			'-o',
			optimized
		],
		{ stdio: 'inherit' }
	);

	rmSync(OUT_SVG, { recursive: true, force: true });
	mkdirSync(OUT_SVG, { recursive: true });
	let total = 0;
	for (const c of codes) {
		const src = join(optimized, `${c}.svg`);
		copyFileSync(src, join(OUT_SVG, `${c}.svg`));
		total += statSync(src).size;
	}

	const licenseText = readdirSync(pkgDir).includes('LICENSE.md')
		? readFileSync(join(pkgDir, 'LICENSE.md'), 'utf8')
		: null;
	if (!licenseText) throw new Error('LICENSE.md missing upstream');
	writeFileSync(
		join(OUT_SVG, 'LICENSE'),
		[
			`Flag artwork in this directory: circle-flags v${CIRCLE_FLAGS_VERSION}`,
			'Source: https://github.com/HatScripts/circle-flags',
			'Optimized with SVGO (multipass). Files are unmodified apart from optimization.',
			'',
			licenseText
		].join('\n')
	);

	mkdirSync(dirname(OUT_TS), { recursive: true });
	mkdirSync(dirname(OUT_RS), { recursive: true });
	const header = `GENERATED by scripts/flags/import.mjs from circle-flags v${CIRCLE_FLAGS_VERSION} — do not edit.`;
	writeFileSync(
		OUT_TS,
		`// ${header}\n\nexport const FLAG_CODES: readonly string[] = ${JSON.stringify(codes)};\n`
	);
	writeFileSync(
		OUT_RS,
		[
			`//! Known flag codes. ${header}`,
			'',
			'/// Lowercase codes accepted in `country_code` (ISO 3166-1 alpha-2 + circle-flags extras).',
			'pub const KNOWN_FLAGS: &[&str] = &[',
			...chunk(codes, 12).map((row) => `    ${row.map((c) => `"${c}"`).join(', ')},`),
			'];',
			''
		].join('\n')
	);

	const kb = (total / 1024).toFixed(1);
	console.log(`flags: ${codes.length} SVG files, ${kb} KiB optimized`);
	if (total > SIZE_BUDGET_BYTES) {
		throw new Error(`flags total ${kb} KiB exceeds budget ${SIZE_BUDGET_BYTES / 1024} KiB`);
	}
} finally {
	rmSync(work, { recursive: true, force: true });
}

function chunk(items, size) {
	const rows = [];
	for (let i = 0; i < items.length; i += size) rows.push(items.slice(i, i + size));
	return rows;
}

"""Country outlines for the overview map, from Natural Earth 110m admin-0 (public domain).

usage: gen-world-borders.py <ne_110m_admin_0_countries.geojson> <out.ts>
Coordinates are in the dot grid's units (see gen-world-map.py), as integers x20; the UI draws
them under `scale(0.05)`.
"""
import json, sys

src, out = sys.argv[1], sys.argv[2]
STEP, LAT0, K = 2.0, 82.0, 20


def pt(lon, lat):
    return round(((lon + 180) / STEP - 0.5) * K), round(((LAT0 - lat) / STEP - 0.5) * K)


def ring_path(ring):
    pts, last = [], None
    for lon, lat in ring:
        p = pt(lon, lat)
        if p != last:
            pts.append(p)
            last = p
    if len(pts) < 3:
        return ''
    d = f'M{pts[0][0]} {pts[0][1]}'
    px, py = pts[0]
    for x, y in pts[1:]:
        d += f'l{x - px} {y - py}'
        px, py = x, y
    return d + 'z'


data = json.load(open(src))
by = {}
for f in data['features']:
    p = f['properties']
    cc = p.get('ISO_A2_EH') if p.get('ISO_A2') in (None, '-99') else p.get('ISO_A2')
    if not cc or cc == '-99':
        continue
    g = f['geometry']
    polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    d = ''.join(ring_path(poly[0]) for poly in polys)
    if d:
        by[cc.lower()] = d
with open(out, 'w') as o:
    o.write('// GENERATED by scripts/gen-world-borders.py from Natural Earth 110m (public domain).\n')
    o.write('// Country outlines in dot-grid units x20, by lowercase ISO 3166-1 alpha-2 code.\n')
    o.write('export const BORDER_SCALE = 0.05;\n')
    o.write('export const OUTLINES: Record<string, string> = ' + json.dumps(by, separators=(',', ':')) + ';\n')
print(len(by), 'countries', sum(len(v) for v in by.values()), 'bytes')
